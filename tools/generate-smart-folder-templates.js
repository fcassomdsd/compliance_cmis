#!/usr/bin/env node
// Generates the pilot Smart Folder profile templates (templates/pilot/*.json)
// from tools/smart-folder-catalog.json.
//
// Why a generator instead of hand-edited JSON: these templates used to be
// several-thousand-node hand-maintained trees (the IDAC/ex-SNA one alone was
// 4,072 nodes), and hand-editing them produced real bugs — e.g. every
// "specialty" leaf under one accidental extra nesting level in that template
// was hardcoded to a single specialty code regardless of the branch's name.
// Building each leaf's query from the same catalog entry used for its
// node id/name makes that class of copy-paste bug impossible.
//
// Scope: the 4 pilot templates (base-comun + the 3 provider profiles).
// The "datos" files were retired separately (superseded by these). Base-
// comun is structurally different from the profiles — shared/cross-
// provider, organized by location rather than provider/specialty — so
// it's generated by a separate function, not the provider/specialty
// builder below, but from the same catalog and with the same governance-
// rule-3 and orphaned-reference self-checks.

import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const catalogPath = path.join(__dirname, "smart-folder-catalog.json");
const outputDir = path.join(__dirname, "..", "templates", "pilot");

const catalog = JSON.parse(readFileSync(catalogPath, "utf8"));

// The catalog carries one flat specialty list (the 16-code Nomenclatura vocabulary;
// the old AGA/SNA/MET domain grouping is retired) and each provider profile
// references it by code. Resolving here rather than duplicating {code,name} per
// profile keeps a profile from drifting away from the catalog's display names,
// and turns a typo'd/retired code into a build failure instead of a silently
// empty Share folder.
const specialtiesByCode = new Map(catalog.specialties.map((s) => [s.code, s]));

function resolveSpecialties(profile) {
  return profile.specialtyCodes.map((code) => {
    const specialty = specialtiesByCode.get(code);
    if (!specialty) {
      throw new Error(
        `Profile "${profile.id}" references specialty code "${code}", which is not in the catalog's flat specialties list`
      );
    }
    return specialty;
  });
}

function slugify(name) {
  return name
    .toLowerCase()
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "");
}

function escapeLucene(value) {
  return String(value).replace(/(["\\])/g, "\\$1");
}

function buildQuery(type, predicates) {
  const parts = [
    `+PATH:"${catalog.path}"`,
    `AND TYPE:"${type}"`,
    ...predicates.map((p) => `AND ${p}`),
  ];
  return parts.join(" ");
}

function specialtyPredicate(code) {
  return `@vso\\:specialtyCode:"${escapeLucene(code)}"`;
}

function providerPredicate(id) {
  return `@vso\\:providerId:"${escapeLucene(id)}"`;
}

// OR-group across a profile's own providers, used to scope the top-level
// General/Por especialidad leaves to this profile's providers — without
// it, those leaves only constrain TYPE+PATH and return every provider's
// records (including other profiles').
function providerSetPredicate(providers) {
  return `(${providers.map((provider) => providerPredicate(provider.id)).join(" OR ")})`;
}

function followUpTypePredicate(value) {
  return `@vso\\:followUpType:"${escapeLucene(value)}"`;
}

function locationCodePredicate(code) {
  return `@vso\\:locationCode:"${escapeLucene(code)}"`;
}

// A leaf node: has `search`, never `nodes` — satisfies operational-map.md
// governance rule 3 (classifier nodes must not carry `search`) because a
// node with children is never also given a search block, by construction.
function leaf(id, name, query) {
  return { id, name, search: { language: "fts-alfresco", query } };
}

function classifier(id, name, nodes) {
  return { id, name, nodes };
}

function buildSpecialtyBranch(idPrefix, type, specialties, extraPredicates) {
  return classifier(`${idPrefix}-por-especialidad`, "Por especialidad", specialties.map((specialty) =>
    leaf(
      `${idPrefix}-por-especialidad-${slugify(specialty.code)}`,
      specialty.name,
      buildQuery(type, [...extraPredicates, specialtyPredicate(specialty.code)])
    )
  ));
}

function buildSectionForScope(idPrefix, section, specialties, extraPredicates) {
  return [
    leaf(`${idPrefix}-general`, "General", buildQuery(section.type, extraPredicates)),
    buildSpecialtyBranch(idPrefix, section.type, specialties, extraPredicates),
  ];
}

function buildSection(profile, section) {
  const idPrefix = `profile-${profile.id}-${section.id}`;
  const specialties = resolveSpecialties(profile);
  const nodes = buildSectionForScope(idPrefix, section, specialties, [providerSetPredicate(profile.providers)]);

  // Single-provider profiles (idac, indomet) skip "Por proveedor" entirely —
  // it would just duplicate "General" for a profile that only ever has
  // one provider.
  if (profile.providers.length > 1) {
    nodes.push(
      classifier(`${idPrefix}-por-proveedor`, "Por proveedor", profile.providers.map((provider) => {
        const providerIdPrefix = `${idPrefix}-por-proveedor-${slugify(provider.name)}`;
        return classifier(
          providerIdPrefix,
          provider.name,
          buildSectionForScope(providerIdPrefix, section, specialties, [providerPredicate(provider.id)])
        );
      }))
    );
  }

  if (section.id === "seguimientos") {
    nodes.push(
      classifier(`${idPrefix}-por-tipo`, "Por tipo", catalog.followUpTypes.map((type) =>
        leaf(
          `${idPrefix}-por-tipo-${slugify(type)}`,
          type,
          buildQuery(section.type, [followUpTypePredicate(type)])
        )
      ))
    );
  }

  return classifier(idPrefix, section.name, nodes);
}

function buildProfileTemplate(profile) {
  return {
    id: `profile-${profile.id}`,
    name: profile.title,
    nodes: catalog.sections.map((section) => buildSection(profile, section)),
  };
}

// base-comun is structurally different from the provider profiles — it's
// the deliberately cross-provider, location-organized view, so it isn't
// built from buildSection (provider/specialty oriented). Kept flat: one
// leaf per location for Inspecciones/Hallazgos (no nested status/risk —
// that's the dashboard's job now), plus Seguimientos' follow-up-type
// facet, which has no location dimension in the source template either.
function buildBaseComunTemplate() {
  const { baseComun, locations, followUpTypes } = catalog;

  const sectionNodes = baseComun.sections.map((section) => {
    const idPrefix = `base-comun-${section.id}`;
    return classifier(idPrefix, section.name, [
      classifier(`${idPrefix}-por-localidad`, "Por localidad", locations.map((location) =>
        leaf(
          `${idPrefix}-por-localidad-${slugify(location.code)}`,
          location.name,
          buildQuery(section.type, [locationCodePredicate(location.code)])
        )
      )),
    ]);
  });

  sectionNodes.push(
    classifier("base-comun-seguimientos", "Seguimientos", [
      classifier("base-comun-seguimientos-por-tipo", "Por tipo", followUpTypes.map((type) =>
        leaf(
          `base-comun-seguimientos-por-tipo-${slugify(type)}`,
          type,
          buildQuery("vso:followUpReport", [followUpTypePredicate(type)])
        )
      )),
    ])
  );

  return { id: "vso-pilot-base-comun", name: baseComun.title, nodes: sectionNodes };
}

// Self-checks: fail loudly rather than emit a template that could
// silently misbehave in Share.
function assertNoSearchOnClassifiers(node, path) {
  const hasChildren = Array.isArray(node.nodes) && node.nodes.length > 0;
  if (hasChildren && node.search) {
    throw new Error(`Governance rule 3 violation: classifier node has a search block at ${path}/${node.id}`);
  }
  if (hasChildren) {
    node.nodes.forEach((child) => assertNoSearchOnClassifiers(child, `${path}/${node.id}`));
  } else if (!node.search) {
    throw new Error(`Leaf node with neither children nor a search block at ${path}/${node.id}`);
  }
}

function collectLeafQueries(node, out) {
  if (node.search) {
    out.push(node.search.query);
  }
  (node.nodes || []).forEach((child) => collectLeafQueries(child, out));
  return out;
}

function assertAllMatch(query, pattern, validValues, label, fieldLabel) {
  for (const match of query.matchAll(pattern)) {
    if (!validValues.has(match[1])) {
      throw new Error(`Orphaned ${fieldLabel} "${match[1]}" in generated query for ${label}: ${query}`);
    }
  }
}

// Checks every occurrence of each field, not just the first — providerId
// in particular can now appear multiple times in one query, OR'd together
// by providerSetPredicate.
function assertNoOrphanReferences(template, label, { providerIds = [], specialtyCodes = [], locationCodes = [] }) {
  const validProviderIds = new Set(providerIds);
  const validSpecialtyCodes = new Set(specialtyCodes);
  const validLocationCodes = new Set(locationCodes);
  const queries = collectLeafQueries(template, []);
  for (const query of queries) {
    assertAllMatch(query, /@vso\\:providerId:"([^"]+)"/g, validProviderIds, label, "providerId");
    assertAllMatch(query, /@vso\\:specialtyCode:"([^"]+)"/g, validSpecialtyCodes, label, "specialtyCode");
    assertAllMatch(query, /@vso\\:locationCode:"([^"]+)"/g, validLocationCodes, label, "locationCode");
  }
}

function writeTemplate(fileName, template) {
  const outputPath = path.join(outputDir, fileName);
  writeFileSync(outputPath, JSON.stringify(template, null, 2) + "\n", "utf8");
  console.log(`Wrote ${outputPath}`);
}

for (const profile of catalog.profiles) {
  const template = buildProfileTemplate(profile);
  assertNoSearchOnClassifiers(template, "");
  assertNoOrphanReferences(template, `profile ${profile.id}`, {
    providerIds: profile.providers.map((p) => p.id),
    specialtyCodes: resolveSpecialties(profile).map((s) => s.code),
  });
  writeTemplate(`vigilancia-pilot-template-profile-${profile.id}.json`, template);
}

const baseComunTemplate = buildBaseComunTemplate();
assertNoSearchOnClassifiers(baseComunTemplate, "");
assertNoOrphanReferences(baseComunTemplate, "base-comun", {
  locationCodes: catalog.locations.map((l) => l.code),
});
writeTemplate("vigilancia-pilot-template-base-comun.json", baseComunTemplate);
